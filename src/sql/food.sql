create table public.food_database (
  food_db_id bigint generated by default as identity not null,
  description text not null,
  protein numeric not null default 0,
  fat numeric not null default 0,
  carb numeric not null default 0,
  calories_extra numeric not null default 0,
  sugar numeric not null default 0,
  fiber numeric not null default 0,
  serving_size numeric not null default 1,
  serving_unit text not null,
  is_active boolean not null default true,
  date date not null default CURRENT_DATE,
  constraint food_database_pkey primary key (food_db_id)
)