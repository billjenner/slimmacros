CREATE TABLE public.exercise (
    exercise_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    video_path TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);


-- Enable Row Level Security
ALTER TABLE public.exercise ENABLE ROW LEVEL SECURITY;

-- ============================================================
-- Allow all access to anon and authenticated roles
-- ============================================================
DROP POLICY IF EXISTS "Allow all access to exercise"
ON public.exercise;

CREATE POLICY "Allow all access to exercise"
ON public.exercise
FOR ALL
TO anon, authenticated
USING (true)
WITH CHECK (true);

-- ============================================================
-- Updated RLS - see all records (not just my own)
-- ============================================================

-- SELECT
DROP POLICY IF EXISTS "Authenticated users can view all exercises"
ON public.exercise;

CREATE POLICY "Authenticated users can view all exercises"
ON public.exercise
FOR SELECT
TO authenticated
USING (true);

-- INSERT
DROP POLICY IF EXISTS "Authenticated users can insert all exercises"
ON public.exercise;

CREATE POLICY "Authenticated users can insert all exercises"
ON public.exercise
FOR INSERT
TO authenticated
WITH CHECK (true);

-- UPDATE
DROP POLICY IF EXISTS "Authenticated users can update all exercises"
ON public.exercise;

CREATE POLICY "Authenticated users can update all exercises"
ON public.exercise
FOR UPDATE
TO authenticated
USING (true)
WITH CHECK (true);

-- DELETE
DROP POLICY IF EXISTS "Authenticated users can delete all exercises"
ON public.exercise;

CREATE POLICY "Authenticated users can delete all exercises"
ON public.exercise
FOR DELETE
TO authenticated
USING (true);

