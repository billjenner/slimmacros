create table public.supplement (
  supplement_id bigint generated by default as identity not null,
  user_id uuid not null,
  description text not null,
  serving_size numeric(8, 2) not null default 1,
  serving_unit text not null default 'other'::text,
  share_with_others boolean not null default false,
  is_active boolean not null default true,
  created_at timestamp with time zone not null default now(),
  constraint supplement_pkey primary key (supplement_id),
  constraint supplement_user_id_fkey foreign KEY (user_id) references auth.users (id) on delete CASCADE,
  constraint supplement_serving_size_check check ((serving_size > (0)::numeric))
) 

