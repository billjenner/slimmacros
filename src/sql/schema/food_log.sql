create table public.food_log (
  food_log_id bigint generated by default as identity not null,
  food_id bigint not null,
  user_id uuid not null,
  servings numeric(8, 2) not null default 1,
  datetime timestamp with time zone not null default now(),
  constraint food_log_pkey1 primary key (food_log_id),
  constraint food_log_food_id_fkey1 foreign KEY (food_id) references food (food_id) on delete CASCADE,
  constraint food_log_user_id_fkey1 foreign KEY (user_id) references auth.users (id) on delete CASCADE,
  constraint food_log_servings_check1 check ((servings > (0)::numeric))
)