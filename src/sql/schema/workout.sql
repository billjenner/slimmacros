create table public.workout (
  workout_id bigint generated by default as identity not null,
  user_id uuid not null,
  type text not null,
  average_workout_time integer null,
  calories_burned integer not null default 0,
  share_with_others boolean not null default false,
  is_active boolean not null default true,
  created_at timestamp with time zone not null default now(),
  constraint workout_pkey primary key (workout_id),
  constraint workout_user_id_fkey foreign KEY (user_id) references auth.users (id) on delete CASCADE,
  constraint workout_average_workout_time_check check (
    (
      (average_workout_time is null)
      or (average_workout_time >= 0)
    )
  ),
  constraint workout_calories_burned_check check ((calories_burned >= 0))
)

create index IF not exists workout_user_id_idx on public.workout using btree (user_id) TABLESPACE pg_default;

create index IF not exists workout_active_idx on public.workout using btree (is_active) TABLESPACE pg_default;

-- ============================================================
-- RLS - workout (all authenticated users)
-- ============================================================

ALTER TABLE public.workout ENABLE ROW LEVEL SECURITY;

-- SELECT
DROP POLICY IF EXISTS "Authenticated users can view all workouts"
ON public.workout;

CREATE POLICY "Authenticated users can view all workouts"
ON public.workout
FOR SELECT
TO authenticated
USING (true);

-- INSERT
DROP POLICY IF EXISTS "Authenticated users can insert all workouts"
ON public.workout;

CREATE POLICY "Authenticated users can insert all workouts"
ON public.workout
FOR INSERT
TO authenticated
WITH CHECK (true);

-- UPDATE
DROP POLICY IF EXISTS "Authenticated users can update all workouts"
ON public.workout;

CREATE POLICY "Authenticated users can update all workouts"
ON public.workout
FOR UPDATE
TO authenticated
USING (true)
WITH CHECK (true);

-- DELETE
DROP POLICY IF EXISTS "Authenticated users can delete all workouts"
ON public.workout;

CREATE POLICY "Authenticated users can delete all workouts"
ON public.workout
FOR DELETE
TO authenticated
USING (true);

GRANT SELECT, INSERT, UPDATE, DELETE
ON public.workout
TO authenticated;