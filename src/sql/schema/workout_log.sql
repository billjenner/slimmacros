create table public.workout_log (
  workout_log_id bigint generated by default as identity not null,
  workout_id bigint not null,
  user_id uuid not null,
  workout_time integer null,
  calories_burned integer not null default 0,
  date date not null default CURRENT_DATE,
  constraint workout_log_pkey primary key (workout_log_id),
  constraint workout_log_user_id_fkey foreign KEY (user_id) references auth.users (id) on delete CASCADE,
  constraint workout_log_workout_id_fkey foreign KEY (workout_id) references workout (workout_id) on delete CASCADE,
  constraint workout_log_calories_burned_check check ((calories_burned >= 0)),
  constraint workout_log_workout_time_check check (
    (
      (workout_time is null)
      or (workout_time >= 0)
    )
  )
)

-- ============================================================
-- RLS - workout_log (all authenticated users)
-- ============================================================

ALTER TABLE public.workout_log ENABLE ROW LEVEL SECURITY;

-- SELECT
DROP POLICY IF EXISTS "Authenticated users can view all workout logs"
ON public.workout_log;

