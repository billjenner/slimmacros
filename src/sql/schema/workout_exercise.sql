create table public.workout_exercise (
  workout_exercise_id bigint generated by default as identity not null,
  workout_id bigint not null,
  exercise_id bigint not null,

  sort_order integer not null default 0,

  -- Workout-specific exercise values
  weight integer null,
  reps integer null,
  sets integer null,
  duration integer null,

  created_at timestamp with time zone not null default now(),

  constraint workout_exercise_pkey
    primary key (workout_exercise_id),

  constraint workout_exercise_workout_id_fkey
    foreign key (workout_id)
    references public.workout (workout_id)
    on delete cascade,

  constraint workout_exercise_exercise_id_fkey
    foreign key (exercise_id)
    references public.exercise (exercise_id)
    on delete restrict
);


